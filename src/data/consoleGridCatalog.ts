export const CONSOLE_GRID_FIELDS: GridField[] = applyLegacySelectOptions(CONSOLE_GRID_FIELDS_RAW)

export function consoleGridFieldById(id: string): GridField | undefined {
  return CONSOLE_GRID_FIELDS.find((x) => x.id === id)
}

export function defaultVisibleConsoleColumnIds(): string[] {
  return CONSOLE_GRID_FIELDS.filter((x) => x.defaultVisible).map((x) => x.id)
}

export function columnableConsoleFields(lobKey = 'ALL'): GridField[] {
  return CONSOLE_GRID_FIELDS.filter((x) => x.columnable && matchesGridLob(x, lobKey))
}

export function searchableConsoleFields(lobKey: string): GridField[] {
  return CONSOLE_GRID_FIELDS.filter((x) => x.searchable && matchesGridLob(x, lobKey))
}

