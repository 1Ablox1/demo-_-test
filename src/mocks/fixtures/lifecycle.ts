export function cloneLifecycle(shipmentId: number): JobLifecycle | null {
  const seed = lifecycleByShipment[shipmentId]
  if (!seed) return null
  const clone = structuredClone(seed)
  const legacyNo = legacyJobNoForShipment(shipmentId)
  if (legacyNo) clone.jobNo = legacyNo
  return clone
}

export function allLifecycleShipments(): number[] {
  return Object.keys(lifecycleByShipment).map(Number)
}
