import type { JobLifecycle } from '@/os/types'

const milestoneDefs = [
  { id: 'quote' as const, label: 'Quote', order: 0 },
  { id: 'booking' as const, label: 'Booking', order: 1 },
  { id: 'documents' as const, label: 'Documents', order: 2 },
  { id: 'charges' as const, label: 'Charges', order: 3 },
  { id: 'invoice' as const, label: 'Invoice', order: 4 },
  { id: 'history' as const, label: 'History', order: 5 },
]

function baseMilestones(
  gatesByMs: Partial<Record<string, string[]>>,
  tasksByMs: Partial<Record<string, string[]>>,
) {
  return milestoneDefs.map((m) => ({
    ...m,
    gateIds: gatesByMs[m.id] ?? [],
    taskIds: tasksByMs[m.id] ?? [],
  }))
}

